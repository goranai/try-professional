"""Generate THIRD_PARTY_SKILLS.md from the lockfile, so it can't drift from what's installed."""

from __future__ import annotations

from .lockfile import Lockfile

HEADER = """# Third-party skills

Generated by `skill-customs attribution` from `skills.lock`. Don't edit by hand.
"""


def _cell(text: str) -> str:
    """Skill names come from outside. Keep them from breaking out of a table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def render_attribution(lock: Lockfile) -> str:
    entries = [lock.entries[key] for key in sorted(lock.entries) if lock.entries[key].host != "local"]
    if not entries:
        return HEADER + "\nNo third-party skills are installed.\n"
    lines = [HEADER, "| Skill | Source | Commit | License | Commercial use | Trust |", "|---|---|---|---|---|---|"]
    for entry in entries:
        source = f"https://github.com/{entry.repo}"
        lines.append(
            f"| {_cell(entry.skill_id)} | {source} | `{entry.commit[:12]}` | {_cell(entry.license_spdx or 'unknown')} "
            f"| {entry.commercial_use} | {entry.trust} |"
        )
    restricted = [e.skill_id for e in entries if e.commercial_use != "allowed"]
    if restricted:
        lines += ["", "## Check before commercial use", ""] + [f"- {_cell(skill)}" for skill in restricted]
    return "\n".join(lines) + "\n"
